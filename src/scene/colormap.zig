//! Turning scalar values into colors.
//!
//! A scalar quantity is one number per vertex, face or point, and the viewer
//! displays it by mapping the range of those numbers onto a color ramp. This
//! module provides the ramps and the range computation; the mapping itself
//! happens in the shader, which samples the ramp as a texture.
//!
//! The ramps are perceptually uniform where possible, so that equal steps in
//! value appear as equal steps in color. They are computed at compile time and cost
//! no runtime work and no allocation.
const std = @import("std");

/// Which color ramp to display a scalar quantity through.
/// ---
/// `viridis` is the default. It is perceptually uniform and reads correctly in
/// greyscale and under the common forms of color blindness. `plasma` is a
/// similar ramp over a warmer range. `turbo` spans more distinguishable hues,
/// which resolves finer structure but implies boundaries the data may not have.
/// `coolwarm` is diverging with a neutral middle, for values that are signed
/// about zero.
pub const Colormap = enum(u8) { viridis, turbo, coolwarm, plasma };

/// The 256-entry RGBA8 ramp for a colormap, as a pointer to compile-time
/// constant data valid for the lifetime of the process. The viewer uploads it
/// as a one-dimensional texture.
pub fn table(cm: Colormap) *const [256][4]u8 {
    return &tables[@backingInt(cm)];
}

/// Computes the range to map a set of scalar values onto a ramp.
///
/// Returns the minimum and maximum of the finite values. NaN and infinity are
/// ignored, so one bad element does not collapse the display of the others.
/// Three degenerate cases return an interval of non-zero width instead: no
/// values, no finite values, and every value identical. The caller can
/// therefore always divide by the width.
pub fn range(values: []const f32) [2]f32 {
    var minimum = std.math.inf(f32);
    var maximum = -std.math.inf(f32);
    for (values) |value| {
        if (!std.math.isFinite(value)) continue;
        minimum = @min(minimum, value);
        maximum = @max(maximum, value);
    }
    if (minimum > maximum) return .{ 0, 1 };
    if (minimum == maximum) {
        const half_width = @max(@abs(minimum) * 0.01, 0.5);
        return .{ minimum - half_width, minimum + half_width };
    }
    return .{ minimum, maximum };
}

