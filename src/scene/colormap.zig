const tables: [4][256][4]u8 = makeTables();

fn makeTables() [4][256][4]u8 {
    @setEvalBranchQuota(10_000);
    var result: [4][256][4]u8 = undefined;
    for (0..256) |i| {
        result[@backingInt(Colormap.viridis)][i] = rgbaFromEmbedded(viridis_rgb, i);
        result[@backingInt(Colormap.plasma)][i] = rgbaFromEmbedded(plasma_rgb, i);
        const t: f32 = @as(f32, @floatFromInt(i)) / 255.0;
        result[@backingInt(Colormap.turbo)][i] = turbo(t);
        result[@backingInt(Colormap.coolwarm)][i] = coolwarm(t);
    }
    // Preserve the published table endpoints; Google's polynomial is an
    // intentionally compact approximation and does not reproduce them exactly.
    result[@backingInt(Colormap.turbo)][0] = .{ 48, 18, 59, 255 };
    result[@backingInt(Colormap.turbo)][255] = .{ 122, 4, 3, 255 };
    return result;
}

fn rgbaFromEmbedded(rgb: []const u8, i: usize) [4]u8 {
    std.debug.assert(rgb.len == 256 * 3);
    return .{ rgb[i * 3], rgb[i * 3 + 1], rgb[i * 3 + 2], 255 };
}

fn turbo(t: f32) [4]u8 {
    const red = horner(t, .{ 0.13572138, 4.61539260, -42.66032258, 132.13108234, -152.94239396, 59.28637943 });
    const green = horner(t, .{ 0.09140261, 2.19418839, 4.84296658, -14.18503333, 4.27729857, 2.82956604 });
    const blue = horner(t, .{ 0.10667330, 12.64194608, -60.58204836, 110.36276771, -89.90310912, 27.34824973 });
    return .{ quantize(red), quantize(green), quantize(blue), 255 };
}

fn horner(t: f32, coefficients: [6]f32) f32 {
    return coefficients[0] + t * (coefficients[1] + t * (coefficients[2] + t * (coefficients[3] + t * (coefficients[4] + t * coefficients[5]))));
}

fn coolwarm(t: f32) [4]u8 {
    const blue = [3]f32{ 59, 76, 192 };
    const white = [3]f32{ 221, 221, 221 };
    const red = [3]f32{ 180, 4, 38 };
    const local = if (t <= 0.5) t * 2.0 else (t - 0.5) * 2.0;
    const a = if (t <= 0.5) blue else white;
    const b = if (t <= 0.5) white else red;
    return .{
        quantize255(a[0] + (b[0] - a[0]) * local),
        quantize255(a[1] + (b[1] - a[1]) * local),
        quantize255(a[2] + (b[2] - a[2]) * local),
        255,
    };
}

fn quantize(value: f32) u8 {
    return quantize255(std.math.clamp(value, 0, 1) * 255.0);
}

fn quantize255(value: f32) u8 {
    return @intFromFloat(@round(std.math.clamp(value, 0, 255)));
}

test "tables have published endpoints and opaque alpha" {
    const expected = [_][2][3]u8{
        .{ .{ 68, 1, 84 }, .{ 253, 231, 37 } },
        .{ .{ 48, 18, 59 }, .{ 122, 4, 3 } },
        .{ .{ 59, 76, 192 }, .{ 180, 4, 38 } },
        .{ .{ 13, 8, 135 }, .{ 240, 249, 33 } },
    };
    inline for (std.enums.values(Colormap), 0..) |cm, cm_i| {
        const lut = table(cm);
        try std.testing.expectEqual(256, lut.len);
        for (lut) |rgba| try std.testing.expectEqual(@as(u8, 255), rgba[3]);
        for (0..3) |channel| {
            try std.testing.expect(channelNear(expected[cm_i][0][channel], lut[0][channel]));
            try std.testing.expect(channelNear(expected[cm_i][1][channel], lut[255][channel]));
        }
    }
}

fn channelNear(expected: u8, actual: u8) bool {
    const difference = @as(i16, expected) - @as(i16, actual);
    return @abs(difference) <= 2;
}

test "range handles normal empty non-finite and constant inputs" {
    try std.testing.expectEqual([2]f32{ -2, 7 }, range(&.{ 7, std.math.nan(f32), -2, 3 }));
    try std.testing.expectEqual([2]f32{ 0, 1 }, range(&.{}));
    try std.testing.expectEqual([2]f32{ 0, 1 }, range(&.{ std.math.nan(f32), std.math.inf(f32) }));
    try std.testing.expectEqual([2]f32{ 3.5, 4.5 }, range(&.{ 4, 4, 4 }));
}
